(def observations
  (mapv
    (fn [entry]
      (let [prefix (str "measurement/" (:directory entry) "/")
            run (read-edn (str prefix "run.edn"))
            request (read-edn (str prefix "request.edn"))
            process (read-edn (str prefix "process.edn"))
            samples (:samples run)
            allocation (:allocation run)
            alloc-samples (:samples allocation)
            count-values #(reduce + (map :count (:workloads %)))
            cpu (fn [s] (- (get-in s [:counters-after :process-cpu-ns]) (get-in s [:counters-before :process-cpu-ns])))
            gc (fn [s k] (- (reduce + (map k (vals (get-in s [:counters-after :gc])))) (reduce + (map k (vals (get-in s [:counters-before :gc]))))))]
        (check! (= :complete (:status run)) "Incomplete worker" entry)
        (check! (= (:context batch) (:context run) (:context request)) "Context mismatch" entry)
        (check! (= (:options batch) (:options request)) "Options mismatch" entry)
        (check! (= request (:request run)) "Request mismatch" entry)
        (check! (= (:case entry) (get-in run [:spec :id])) "Wrong scenario" entry)
        (check! (= (:process entry) process) "Process manifest mismatch" entry)
        (check! (and (zero? (:exit-status process)) (not (:timed-out? process))) "Worker failed" entry)
        (check! (= (:pid process) (get-in run [:process :pid])) "Wrong process" entry)
        (check! (= :passed (:preflight run) (:postflight run)) "Validation missing" entry)
        (check! (= 12 (count samples)) "Wrong sample count" entry)
        (check! (= (avg (map :elapsed-ns samples)) (:mean-ns run) (:mean-ns entry)) "Wrong time aggregate" entry)
        (check! (and (>= (count (:warmup run)) 3) (>= (reduce + (map :elapsed-ns (:warmup run))) 1e10)) "Insufficient warmup" entry)
        (check! (= :measured (:status allocation)) "Missing allocation" entry)
        (check! (= :passed (get-in allocation [:probe :status])) "Allocation probe failed" entry)
        (check! (<= (get-in allocation [:probe :expected-payload-bytes]) (get-in allocation [:probe :observed-bytes])) "Allocation probe insufficient" entry)
        (check! (= 5 (count alloc-samples)) "Wrong allocation count" entry)
        (doseq [s (concat samples alloc-samples)]
          (check! (= :count-and-sum (:validation s)) "Unvalidated sample" entry)
          (check! (pos? (:elapsed-ns s)) "Invalid elapsed time" entry)
          (check! (= (count-values (first samples)) (count-values s)) "Work count changed" entry))
        (doseq [s alloc-samples :let [a (:allocation s)]]
          (check! (every? #(and (number? %) (<= 0 %)) (vals a)) "Invalid allocation count" entry)
          (check! (= (:setup-and-transfer-bytes a) (+ (:setup-bytes a) (:transfer-bytes a))) "Allocation boundary mismatch" entry))
        (merge (select-keys entry [:case :framework :fork :directory])
          {:pid (:pid process) :mean-ms (/ (:mean-ns entry) 1e6)
           :sample-ms (mapv #(/ (:elapsed-ns %) 1e6) samples)
           :delivered-values (count-values (first samples))
           :allocation-bytes-per-value (mapv #(/ (double (get-in % [:allocation :transfer-bytes])) (count-values %)) alloc-samples)
           :mean-transfer-bytes-per-value (:mean-transfer-bytes-per-value allocation)
           :mean-setup-bytes (:mean-setup-bytes allocation)
           :mean-cpu-ms (/ (avg (map cpu samples)) 1e6)
           :sample-gc-ms (mapv #(gc % :ms) samples)
           :sample-gc-count (mapv #(gc % :count) samples)})))
    (:runs batch)))
(check! (= 8 (count (distinct (map :pid observations)))) "Reused JVM" {})
(def comparisons
  (mapv
    (fn [[id rows]]
      (let [arms (group-by :framework rows)
            stats (fn [rs]
                    (let [ts (map :mean-ms rs) m (median ts)]
                      {:jvm-mean-ms (mapv :mean-ms rs) :median-ms m
                       :spread-percent (* 100.0 (/ (- (apply max ts) (apply min ts)) m))
                       :jvm-allocation-bytes-per-value (mapv :mean-transfer-bytes-per-value rs)
                       :median-allocation-bytes-per-value (median (map :mean-transfer-bytes-per-value rs))
                       :median-setup-bytes (median (map :mean-setup-bytes rs))
                       :median-cpu-ms (median (map :mean-cpu-ms rs))}))
            q (stats (:quiescent arms)) a (stats (:core-async arms))]
        {:case id :quiescent q :core-async a
         :time-ratio (/ (:median-ms a) (:median-ms q))
         :allocation-ratio (/ (:median-allocation-bytes-per-value a) (:median-allocation-bytes-per-value q))
         :paired-time-ratios (mapv (fn [[_ rs]] (let [m (into {} (map (juxt :framework :mean-ms)) rs)] (/ (:core-async m) (:quiescent m)))) (sort-by key (group-by :fork rows)))}))
    (sort-by (comp name key) (group-by :case observations))))
