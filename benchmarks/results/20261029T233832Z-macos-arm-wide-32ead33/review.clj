(def root (first *command-line-args*))
(defn read-edn [p] (edn/read-string (slurp (io/file root p))))
(def batch (read-edn "measurement/batch.edn"))
(defn check! [test msg data] (when-not test (throw (ex-info msg data))))
(defn avg [xs] (/ (double (reduce + xs)) (count xs)))
(defn median [xs] (let [v (vec (sort xs)) n (count v) m (quot n 2)] (if (odd? n) (v m) (/ (+ (v (dec m)) (v m)) 2.0))))
(defn sha [p] (apply str (map #(format "%02x" (bit-and 255 %)) (.digest (MessageDigest/getInstance "SHA-256") (java.nio.file.Files/readAllBytes (.toPath (io/file p)))))))
